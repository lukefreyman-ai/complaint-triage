"""
taxonomy.py — The closed list of product categories the AI is allowed to choose from.

Why this file matters so much:
If we just asked the AI to "guess the product category" with no constraints,
it might invent labels like "Fraud" or "Card Issue" that don't match any CFPB
category. Then when we compare its answer to the ground truth, we couldn't
tell if it was "wrong" or just "phrased it differently." The whole benchmark
would be meaningless.

So instead, we:
  1. Look at the *exact* set of `product` values that actually appear in our
     fetched data (VALID_PRODUCTS below).
  2. Force the AI to pick one of those exact strings (done in classify.py).
  3. Provide normalize_product() as a safety net — it cleans up trivial
     formatting differences (extra whitespace, wrong case) and maps a few
     common near-miss phrasings back to the canonical label, in case the
     model paraphrases slightly despite our instructions.
"""

import json
from pathlib import Path

ROOT = Path(__file__).parent.parent
RAW_DATA_FILE = ROOT / "data" / "raw_complaints.json"


# ── The closed list ──────────────────────────────────────────────────────────
# This was generated by running extract_products_from_data() against our
# actual data/raw_complaints.json pull (see the __main__ block below). It is
# hardcoded here — not recomputed on every import — so the taxonomy stays
# stable even if you re-fetch a different batch of complaints later. If you
# fetch a new dataset and want to regenerate this list, run:
#     python src/taxonomy.py
# and paste the printed list back in here.
VALID_PRODUCTS = [
    "Checking or savings account",
    "Credit card",
    "Credit reporting or other personal consumer reports",
    "Debt collection",
    "Money transfer, virtual currency, or money service",
    "Mortgage",
    "Payday loan, title loan, personal loan, or advance loan",
    "Student loan",
    "Vehicle loan or lease",
]


# ── Near-miss mapping ────────────────────────────────────────────────────────
# Keys are lowercased "common variants" (things a model might say instead of
# the canonical label). Values are the exact canonical string from
# VALID_PRODUCTS. This mostly covers older/shorter CFPB category names, since
# the CFPB has renamed some products over the years, and a model trained on
# older data might default to the old name.
NEAR_MISS_MAP = {
    "credit reporting": "Credit reporting or other personal consumer reports",
    "credit reporting, credit repair services, or other personal consumer reports":
        "Credit reporting or other personal consumer reports",
    "credit reports": "Credit reporting or other personal consumer reports",
    "credit cards": "Credit card",
    "credit card or prepaid card": "Credit card",
    "payday loan": "Payday loan, title loan, personal loan, or advance loan",
    "payday loan, title loan, or personal loan":
        "Payday loan, title loan, personal loan, or advance loan",
    "personal loan": "Payday loan, title loan, personal loan, or advance loan",
    "title loan": "Payday loan, title loan, personal loan, or advance loan",
    "money transfers": "Money transfer, virtual currency, or money service",
    "money transfer": "Money transfer, virtual currency, or money service",
    "virtual currency": "Money transfer, virtual currency, or money service",
    "vehicle loan": "Vehicle loan or lease",
    "vehicle lease": "Vehicle loan or lease",
    "auto loan": "Vehicle loan or lease",
    "car loan": "Vehicle loan or lease",
    "checking account": "Checking or savings account",
    "savings account": "Checking or savings account",
    "bank account or service": "Checking or savings account",
    "student loans": "Student loan",
}


def normalize_product(raw: str) -> str | None:
    """
    Clean up a product string returned by the model (or typed by a user in
    the Streamlit app) and map it to the exact canonical label.

    Returns the canonical string from VALID_PRODUCTS, or None if we can't
    confidently match it to anything. Callers should treat None as "invalid
    category" — e.g. classify.py records it as a wrong/unmatched prediction
    rather than silently accepting a made-up label.
    """
    if not raw:
        return None

    # Lowercase + strip surrounding whitespace, and collapse any internal
    # double-spaces, so "  Credit Card " and "credit card" both normalize
    # the same way.
    cleaned = " ".join(raw.strip().lower().split())

    # Build a lowercase -> canonical lookup once per call is fine at our
    # scale (9 items), so we don't need to cache it.
    canonical_by_lower = {p.lower(): p for p in VALID_PRODUCTS}

    # 1. Exact match (case-insensitive) — the common, expected case.
    if cleaned in canonical_by_lower:
        return canonical_by_lower[cleaned]

    # 2. Known near-miss phrasing.
    if cleaned in NEAR_MISS_MAP:
        return NEAR_MISS_MAP[cleaned]

    # 3. No match — let the caller decide how to handle it.
    return None


def extract_products_from_data() -> list[str]:
    """
    Read data/raw_complaints.json and return the sorted, deduplicated list
    of `product` values actually present in it. This is how VALID_PRODUCTS
    above was originally generated.
    """
    if not RAW_DATA_FILE.exists():
        raise FileNotFoundError(
            f"{RAW_DATA_FILE} not found — run `python src/fetch_data.py` first."
        )

    with open(RAW_DATA_FILE) as f:
        records = json.load(f)

    products = sorted({r["product"] for r in records})
    return products


# ── Run directly ─────────────────────────────────────────────────────────────
# Re-derives the taxonomy from the current data file and prints it, so you
# can eyeball it and compare against VALID_PRODUCTS above (e.g. after
# re-fetching a new dataset).
if __name__ == "__main__":
    extracted = extract_products_from_data()

    print(f"── Taxonomy extracted from {RAW_DATA_FILE.name} ──────────────────────")
    print(f"  {len(extracted)} distinct product categories:\n")
    for p in extracted:
        print(f"  - {p}")

    if extracted == VALID_PRODUCTS:
        print("\nMatches the hardcoded VALID_PRODUCTS list. Nothing to update.")
    else:
        print("\nWARNING: this differs from the hardcoded VALID_PRODUCTS list above.")
        print("If you've fetched new data, copy the list below into VALID_PRODUCTS:\n")
        print("VALID_PRODUCTS = [")
        for p in extracted:
            print(f'    "{p}",')
        print("]")
